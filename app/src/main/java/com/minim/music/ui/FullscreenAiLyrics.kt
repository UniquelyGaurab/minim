package com.minim.music.ui

import android.content.res.ColorStateList
import android.graphics.drawable.GradientDrawable
import android.view.View
import android.widget.FrameLayout
import android.widget.ImageView
import android.widget.LinearLayout
import android.widget.TextView
import androidx.core.graphics.ColorUtils
import com.minim.music.R
import com.minim.music.data.ai.AiLyricsResult
import com.minim.music.data.ai.GeminiProblem
import kotlinx.coroutines.CancellationException
import kotlinx.coroutines.CoroutineScope
import kotlinx.coroutines.Job
import kotlinx.coroutines.launch

/**
 * 5.8.1 (update 53): Gemini lyrics inside full screen lyrics. Never automatic: a song with no
 * lyrics shows the offer, and nothing is sent until it's tapped. While Gemini works the middle
 * shows the cover-colour bars, "Listening…" and Cancel. AI lyrics carry one small line above
 * the bar ("Generated by AI · might not be accurate"), never one per line, and a regenerate
 * button top left.
 *
 * The request itself lives in the app (MainActivity hands it to [Host]), so leaving the screen
 * or the song doesn't throw away a request on its way; this class only shows it.
 */
class FullscreenAiLyrics(
    private val overlay: View,
    private val scope: CoroutineScope,
    private val host: Host,
) {
    interface Host {
        /** Asks Gemini (or reuses the saved copy). On [AiLyricsResult.Done] the screen already has the lyrics. */
        suspend fun requestAiLyrics(songId: String, regenerate: Boolean): AiLyricsResult
        fun isAiLyricsWorking(songId: String): Boolean
        fun cancelAiLyrics(songId: String)
        /** Opens Settings at the Gemini key. */
        fun openGeminiKeySettings()
        fun showNote(text: String)
        fun tapHaptic(v: View)
        fun animationsOn(): Boolean
        /** The screen is open and settled (taps count). */
        fun canTap(): Boolean
    }

    /** What the middle shows when a song has no lyrics. */
    sealed class Panel {
        object Offer : Panel()
        object Working : Panel()
        data class Error(val result: AiLyricsResult) : Panel()
    }

    private val res = overlay.resources
    val panel: LinearLayout = overlay.findViewById(R.id.fs_ai_panel)
    private val title: TextView = overlay.findViewById(R.id.fs_ai_head)
    private val wait: AiListeningView = overlay.findViewById(R.id.fs_ai_wait)
    private val action: TextView = overlay.findViewById(R.id.fs_ai_action)
    private val note: TextView = overlay.findViewById(R.id.fs_ai_note)
    val badge: TextView = overlay.findViewById(R.id.fs_ai_badge)
    val redo: ImageView = overlay.findViewById(R.id.fs_ai_redo)
    private val actionBg = GradientDrawable().apply { cornerRadius = 999f }
    private val redoBg = GradientDrawable().apply { shape = GradientDrawable.OVAL }

    private var ink = 0xFFFFFFFF.toInt()
    private var cover = intArrayOf()

    /** The song the offer is for (null: no offer, e.g. lyrics exist, loading, or a tape). */
    var songId: String? = null
        private set
    /** The panel's state for [songId]. */
    var state: Panel = Panel.Offer
        private set
    /** True while the shown lyrics are AI ones (badge + regenerate). */
    var showingAi = false
        private set
    /** Regenerating over AI lyrics that stay saved until new ones work. */
    var regenerating = false
        private set
    /** Called when the list must hide / show again around a regenerate. */
    var onListHidden: ((Boolean) -> Unit)? = null

    private var job: Job? = null
    private var panelWanted = false

    init {
        action.background = actionBg
        action.setOnClickListener { onAction() }
        redo.setOnClickListener { onRedo() }
    }

    /** MainActivity: the song changed, or its lyrics did. [id] null = no offer. */
    fun setSong(id: String?) {
        if (id == songId) return
        job?.cancel()
        job = null
        if (regenerating) { regenerating = false; onListHidden?.invoke(false) }
        songId = id
        state = if (id != null && host.isAiLyricsWorking(id)) Panel.Working else Panel.Offer
        if (state == Panel.Working) attach(id!!, regenerate = false)
        render()
    }

    /** The lyrics now on screen are AI ones (or not). */
    fun setShowingAi(ai: Boolean) {
        if (ai && regenerating) {
            regenerating = false
            onListHidden?.invoke(false)
        }
        showingAi = ai
        render()
    }

    /** FullscreenLyrics: show the panel in the middle (no lyrics), or not. */
    fun setPanelWanted(wanted: Boolean) {
        panelWanted = wanted
        render()
    }

    val panelShown: Boolean get() = panel.visibility == View.VISIBLE

    fun setInk(i: Int) {
        ink = i
        style()
    }

    /** The cover's colours for the waiting bars (bg, fg, muted of the playing song's palette). */
    fun setCoverColors(p: Pal) {
        cover = intArrayOf(p.fg, p.muted, p.bg)
        style()
    }

    fun setAlpha(a: Float, lift: Float) {
        panel.alpha = a
        panel.translationY = lift
        badge.alpha = a * BADGE_ALPHA
        redo.alpha = a
    }

    fun place(insetTop: Int, insetBottom: Int, topDp: Float, badgeBottomPx: Int) {
        (redo.layoutParams as? FrameLayout.LayoutParams)?.let {
            val top = insetTop + dp(topDp).toInt()
            if (it.topMargin != top) { it.topMargin = top; redo.layoutParams = it }
        }
        (badge.layoutParams as? FrameLayout.LayoutParams)?.let {
            val bottom = insetBottom + badgeBottomPx
            if (it.bottomMargin != bottom) { it.bottomMargin = bottom; badge.layoutParams = it }
        }
    }

    // ------------------------------------------------------------------------------------------

    private fun onAction() {
        if (!host.canTap()) return
        val id = songId ?: return
        host.tapHaptic(action)
        when (val s = state) {
            Panel.Working -> {
                host.cancelAiLyrics(id)
                job?.cancel()
                job = null
                state = Panel.Offer
                if (regenerating) { regenerating = false; onListHidden?.invoke(false) }
                render()
            }
            is Panel.Error -> if (opensSettings(s.result)) host.openGeminiKeySettings() else start(id, regenerate = false)
            Panel.Offer -> start(id, regenerate = false)
        }
    }

    private fun onRedo() {
        if (!host.canTap() || !showingAi || regenerating) return
        val id = songId ?: return
        host.tapHaptic(redo)
        regenerating = true
        onListHidden?.invoke(true)
        start(id, regenerate = true)
    }

    private fun start(id: String, regenerate: Boolean) {
        state = Panel.Working
        render()
        attach(id, regenerate)
    }

    private fun attach(id: String, regenerate: Boolean) {
        job?.cancel()
        job = scope.launch {
            val result = try {
                host.requestAiLyrics(id, regenerate)
            } catch (e: CancellationException) {
                throw e
            } catch (e: Exception) {
                AiLyricsResult.Unusable
            }
            if (songId != id) return@launch
            job = null
            if (result is AiLyricsResult.Done) {
                // MainActivity already put the lyrics on screen (setShowingAi ran)
                state = Panel.Offer
                if (regenerating) { regenerating = false; onListHidden?.invoke(false) }
                render()
                return@launch
            }
            if (regenerating) {
                regenerating = false
                onListHidden?.invoke(false)
                state = Panel.Offer
                host.showNote(res.getString(R.string.ai_lyrics_regen_failed, res.getString(messageFor(result))))
            } else {
                state = Panel.Error(result)
            }
            render()
        }
    }

    private fun render() {
        val showPanel = songId != null && ((panelWanted && !showingAi) || regenerating)
        panel.visibility = if (showPanel) View.VISIBLE else View.GONE
        val aiOn = showingAi && !regenerating
        badge.visibility = if (aiOn) View.VISIBLE else View.GONE
        redo.visibility = if (aiOn && songId != null) View.VISIBLE else View.GONE
        when (val s = state) {
            Panel.Offer -> {
                title.setText(R.string.fs_no_lyrics)
                title.visibility = View.VISIBLE
                wait.visibility = View.GONE
                action.setText(R.string.ai_lyrics_get)
                note.setText(R.string.ai_lyrics_offer_note)
                note.visibility = View.VISIBLE
            }
            Panel.Working -> {
                title.visibility = View.GONE
                wait.visibility = View.VISIBLE
                action.setText(R.string.ai_lyrics_cancel)
                note.setText(R.string.ai_lyrics_listening)
                note.visibility = View.VISIBLE
            }
            is Panel.Error -> {
                title.visibility = View.VISIBLE
                wait.visibility = View.GONE
                if (s.result is AiLyricsResult.NoKey) {
                    title.setText(R.string.ai_lyrics_need_key)
                    note.setText(R.string.ai_lyrics_need_key_note)
                    note.visibility = View.VISIBLE
                } else {
                    title.setText(messageFor(s.result))
                    note.setText(R.string.ai_lyrics_offer_note)
                    note.visibility = View.VISIBLE
                }
                action.setText(actionFor(s.result))
            }
        }
        wait.running = state == Panel.Working && showPanel
        wait.moving = host.animationsOn()
        if (state == Panel.Working && showPanel) panel.announceForAccessibility(res.getString(R.string.ai_lyrics_listening))
        style()
    }

    private fun style() {
        title.setTextColor(ColorUtils.setAlphaComponent(ink, (255 * 0.85f).toInt()))
        note.setTextColor(ColorUtils.setAlphaComponent(ink, (255 * NOTE_ALPHA).toInt()))
        action.setTextColor(ink)
        actionBg.setColor(ColorUtils.setAlphaComponent(ink, ACTION_FILL))
        badge.setTextColor(ink)
        redo.imageTintList = ColorStateList.valueOf(ink)
        redoBg.setColor(ColorUtils.setAlphaComponent(ink, REDO_FILL))
        if (redo.background !== redoBg) redo.background = redoBg
        wait.setColors(waitColors(cover, ink))
    }

    private fun dp(v: Float): Float = v * res.displayMetrics.density

    companion object {
        const val BADGE_ALPHA = 0.55f
        const val NOTE_ALPHA = 0.55f
        const val ACTION_FILL = 0x2E
        const val REDO_FILL = 0x1F

        /** Errors whose fix is in Settings (the key or the model): the button goes there. */
        fun opensSettings(r: AiLyricsResult): Boolean = r is AiLyricsResult.NoKey ||
            (r is AiLyricsResult.Failed && (r.problem is GeminiProblem.BadKey || r.problem is GeminiProblem.UnknownModel))

        fun actionFor(r: AiLyricsResult): Int = when {
            r is AiLyricsResult.NoKey -> R.string.ai_lyrics_open_settings
            opensSettings(r) -> R.string.ai_lyrics_check_key
            else -> R.string.ai_lyrics_retry
        }

        /** The short, friendly line for each way it can go wrong. */
        fun messageFor(r: AiLyricsResult): Int = when (r) {
            is AiLyricsResult.Done -> R.string.ai_lyrics_err_other
            AiLyricsResult.NoKey -> R.string.ai_lyrics_need_key
            AiLyricsResult.Instrumental -> R.string.ai_lyrics_err_instrumental
            AiLyricsResult.Unusable -> R.string.ai_lyrics_err_unusable
            AiLyricsResult.NoAudio -> R.string.ai_lyrics_err_audio
            AiLyricsResult.TooLong -> R.string.ai_lyrics_err_long
            AiLyricsResult.TimedOut -> R.string.ai_lyrics_err_timeout
            AiLyricsResult.Refused -> R.string.ai_lyrics_err_refused
            is AiLyricsResult.Failed -> when (r.problem) {
                GeminiProblem.BadKey -> R.string.ai_lyrics_err_key
                GeminiProblem.Quota -> R.string.ai_lyrics_err_quota
                GeminiProblem.Offline -> R.string.ai_lyrics_err_offline
                GeminiProblem.Busy -> R.string.ai_lyrics_err_busy
                GeminiProblem.Region -> R.string.ai_lyrics_err_region
                GeminiProblem.Blocked -> R.string.ai_lyrics_err_refused
                is GeminiProblem.UnknownModel -> R.string.ai_lyrics_err_model
                else -> R.string.ai_lyrics_err_other
            }
        }

        /**
         * The bars' colours: the cover's own colours, each pulled toward the lyric ink just enough
         * to read against the blurred cover (contrast 2:1 or better with the opposite ink).
         */
        fun waitColors(cover: IntArray, ink: Int): IntArray {
            if (cover.isEmpty()) return intArrayOf(ink)
            val other = if (ColorUtils.calculateLuminance(ink) > 0.5) 0xFF000000.toInt() else 0xFFFFFFFF.toInt()
            return cover.map { c ->
                var t = 0f
                var out = c or 0xFF000000.toInt()
                while (ColorUtils.calculateContrast(out, other) < 2.0 && t < 1f) {
                    t += 0.1f
                    out = ColorUtils.blendARGB(c or 0xFF000000.toInt(), ink or 0xFF000000.toInt(), t)
                }
                out
            }.toIntArray()
        }
    }
}
