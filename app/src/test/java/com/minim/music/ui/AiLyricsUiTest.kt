package com.minim.music.ui

import android.content.Context
import androidx.core.graphics.ColorUtils
import androidx.test.core.app.ApplicationProvider
import com.minim.music.R
import com.minim.music.data.ai.AiLyricsResult
import com.minim.music.data.ai.GeminiProblem
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertTrue
import org.junit.Test
import org.junit.runner.RunWith
import org.robolectric.RobolectricTestRunner
import org.robolectric.annotation.Config

/** 5.8.1 (update 53): the Gemini lyrics messages, buttons and waiting colours. */
@RunWith(RobolectricTestRunner::class)
@Config(sdk = [34], application = android.app.Application::class)
class AiLyricsUiTest {

    private val ctx = ApplicationProvider.getApplicationContext<Context>()

    private val all = listOf(
        AiLyricsResult.NoKey, AiLyricsResult.Instrumental, AiLyricsResult.Unusable, AiLyricsResult.NoAudio,
        AiLyricsResult.TooLong, AiLyricsResult.TimedOut, AiLyricsResult.Refused,
        AiLyricsResult.Failed(GeminiProblem.BadKey), AiLyricsResult.Failed(GeminiProblem.Quota),
        AiLyricsResult.Failed(GeminiProblem.Offline), AiLyricsResult.Failed(GeminiProblem.Busy),
        AiLyricsResult.Failed(GeminiProblem.Region), AiLyricsResult.Failed(GeminiProblem.Blocked),
        AiLyricsResult.Failed(GeminiProblem.UnknownModel("x")),
    )

    @Test fun everyProblemHasAShortFriendlyLine() {
        for (r in all) {
            val text = ctx.getString(FullscreenAiLyrics.messageFor(r))
            assertTrue("$r: $text", text.length in 10..90)
            assertFalse("$r: $text", text.contains("Exception") || text.contains("HTTP"))
        }
        assertEquals("Gemini didn't accept your API key. Check it in Settings.", ctx.getString(FullscreenAiLyrics.messageFor(AiLyricsResult.Failed(GeminiProblem.BadKey))))
        assertEquals("You've hit your Gemini limit for now. Try again later.", ctx.getString(FullscreenAiLyrics.messageFor(AiLyricsResult.Failed(GeminiProblem.Quota))))
        assertEquals("Couldn't reach Gemini. Check your connection.", ctx.getString(FullscreenAiLyrics.messageFor(AiLyricsResult.Failed(GeminiProblem.Offline))))
        assertEquals("Gemini took too long. Try again.", ctx.getString(FullscreenAiLyrics.messageFor(AiLyricsResult.TimedOut)))
    }

    @Test fun keyAndModelProblemsGoToSettingsTheRestRetry() {
        assertEquals(R.string.ai_lyrics_open_settings, FullscreenAiLyrics.actionFor(AiLyricsResult.NoKey))
        assertEquals(R.string.ai_lyrics_check_key, FullscreenAiLyrics.actionFor(AiLyricsResult.Failed(GeminiProblem.BadKey)))
        assertEquals(R.string.ai_lyrics_check_key, FullscreenAiLyrics.actionFor(AiLyricsResult.Failed(GeminiProblem.UnknownModel("x"))))
        for (r in all.filterNot { FullscreenAiLyrics.opensSettings(it) }) {
            assertEquals("$r", R.string.ai_lyrics_retry, FullscreenAiLyrics.actionFor(r))
        }
        assertEquals("Generated by AI · might not be accurate", ctx.getString(R.string.ai_lyrics_disclaimer))
    }

    @Test fun theWaitingBarsUseTheCoverColoursAndStayVisible() {
        val cover = intArrayOf(0xFF102030.toInt(), 0xFFF0E0C0.toInt(), 0xFF808080.toInt())
        for (ink in intArrayOf(0xFFFFFFFF.toInt(), 0xFF111111.toInt())) {
            val out = FullscreenAiLyrics.waitColors(cover, ink)
            assertEquals(3, out.size)
            val other = if (ColorUtils.calculateLuminance(ink) > 0.5) 0xFF000000.toInt() else 0xFFFFFFFF.toInt()
            out.forEach { assertTrue(ColorUtils.calculateContrast(it, other) >= 2.0 || it == ink) }
        }
        // a colour that already reads is left exactly as the cover has it
        assertEquals(0xFFF0E0C0.toInt(), FullscreenAiLyrics.waitColors(intArrayOf(0xFFF0E0C0.toInt()), 0xFFFFFFFF.toInt())[0])
        assertEquals(1, FullscreenAiLyrics.waitColors(intArrayOf(), 0xFFFFFFFF.toInt()).size)
    }

    @Test fun theBarsMoveWithinTheirBoxAndRestWhenStill() {
        for (i in 0 until AiListeningView.BARS) {
            var min = 1f
            var max = 0f
            for (k in 0..100) {
                val l = AiListeningView.barLevel(i, k / 100f, moving = true)
                assertTrue(l in 0.2f..1f)
                min = minOf(min, l); max = maxOf(max, l)
            }
            assertTrue(max - min > 0.3f)
            assertEquals(AiListeningView.REST_LEVEL, AiListeningView.barLevel(i, 0.4f, moving = false))
        }
    }
}
